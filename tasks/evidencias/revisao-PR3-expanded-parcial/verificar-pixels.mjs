import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'../../..'),runtime=path.resolve(process.argv[2]);
const require=createRequire(path.join(root,'controle-financeiro-frontend/package.json')),sharp=require('sharp');
const source=path.join(runtime,'worktree-original/browsers/IntegratedMilestoneBrowserReviewTest/visual-360-investments.png');
const hash=b=>createHash('sha256').update(b).digest('hex');
const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const at=(x,y)=>[...data.subarray((y*info.width+x)*info.channels,(y*info.width+x)*info.channels+info.channels)];
const background=at(350,790);let different=0;
for(let y=100;y<790;y++)for(let x=0;x<360;x++)if(at(x,y).some((n,i)=>i<3&&Math.abs(n-background[i])>5))different++;
const preview=path.join(runtime,'pixel-preview.png');assert.ok(!fs.existsSync(preview));
await sharp(data,{raw:{width:info.width,height:info.height,channels:info.channels}}).png().toFile(preview);
const normalized=await sharp(preview).ensureAlpha().raw().toBuffer();assert.equal(hash(data),hash(normalized));
const result={source,sourceSha256:hash(fs.readFileSync(source)),decoder:'installed sharp; raw RGBA followed by lossless PNG encoding',width:info.width,height:info.height,decodedPixelsSha256:hash(data),preview,previewSha256:hash(fs.readFileSync(preview)),previewPixelsSha256:hash(normalized),identicalDecodedPixels:true,bodyPixelsDifferentFromBackground:different,background,samples:[[50,200],[60,300],[100,600],[100,610]].map(([x,y])=>({x,y,rgba:at(x,y)})),limit:'Pixel variation alone is not a content oracle; inspect normalized preview and API/text/identity together.'};
fs.writeFileSync(path.join(runtime,'pixel-decoding.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});

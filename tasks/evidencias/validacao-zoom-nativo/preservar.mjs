import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';

const [mode,arg]=process.argv.slice(2);
assert.ok(arg,'runtime required');
const root=path.resolve(import.meta.dirname,'../../..'), runtime=path.resolve(arg);
const git=(cwd,...args)=>execFileSync('git',['-c','core.longpaths=true',...args],{cwd,encoding:'utf8',windowsHide:true}).trim();
const main=path.dirname(git(root,'rev-parse','--path-format=absolute','--git-common-dir'));
const parent=path.resolve(main,'../controle-financeiro-runtimes/preparacao-adocao');
assert.equal(path.dirname(runtime),parent);
assert.match(path.basename(runtime),/^zoom-nativo-[a-z0-9-]+$/);
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const read=file=>JSON.parse(fs.readFileSync(file,'utf8').replace(/^\uFEFF/,''));
const priorPath=path.join(parent,'revalidacao-rr3-01-v2-01','initial.json');
const prior=read(priorPath);
assert.equal(prior.files.length,1087);
for(const item of prior.files) assert.equal(hash(path.join(root,item.file)),item.sha256,item.file);
assert.equal(prior.protected97.length,97);
for(const item of prior.protected97) assert.equal(hash(path.resolve(main,item.file)),item.sha256,item.file);
const manifest36Path=path.join(root,'tasks/evidencias/saneamento-PR3-expanded/inventario.json');
const manifest36=read(manifest36Path);
const changes=prior.originals7;
assert.equal(manifest36.files.length,36);
assert.equal(changes.length,7);
const byFile=new Map(changes.map(item=>[item.file,item]));
for(const item of manifest36.files) assert.equal(hash(path.join(root,item.file)),byFile.get(item.file)?.after??item.sha256,item.file);
for(const item of changes) assert.equal(hash(item.archivedBefore),item.before,item.archivedBefore);
const old1053=read(prior.manifest1053.path);
assert.equal(old1053.files.length,1053);
assert.equal(hash(prior.manifest1053.path),prior.manifest1053.sha256);
const authorized=prior.manifest1053.files.filter(item=>item.authorizedDelta);
assert.equal(authorized.length,2);
const allowed=new Map(authorized.map(item=>[item.file,item]));
for(const item of old1053.files) {
  const delta=allowed.get(item.file);
  assert.equal(hash(path.join(root,item.file)),delta?.candidate??item.sha256,item.file);
  if(delta) assert.equal(hash(delta.archived),item.sha256,delta.archived);
}
const publication='C:/Users/Aluga.com/.codex/worktrees/publicacao-limpa/controle-financeiro';
const state=cwd=>({head:git(cwd,'rev-parse','HEAD'),branch:git(cwd,'branch','--show-current'),status:git(cwd,'status','--short'),readme:hash(path.join(cwd,'README.md'))});
assert.equal(state(main).readme,'6235da8e1d2247dad2c585fe7b2e7b0d2fd41f47414a4a2701b20f7fbf7d12ca');
assert.equal(state(root).readme,'e7d3458fbd8ac227520be27996ce23c73e8c3be2086d8cfbd51ad59568f4cee0');
assert.ok(!fs.existsSync(path.join(main,'.r3')));
assert.ok(!fs.existsSync(path.join(root,'.r3')));
assert.equal(state(root).branch,'codex/saneamento-pr3-expanded');
git(root,'merge-base','--is-ancestor','f09e69a6511a5772ea9052da7509a8930ae88d17','HEAD');
const manifests={prior1087:{path:priorPath,sha256:hash(priorPath)},manifest36:{path:manifest36Path,sha256:hash(manifest36Path)},manifest1053:{path:prior.manifest1053.path,sha256:hash(prior.manifest1053.path)}};
const summary={historical1087:1087,protected97:97,records36:36,archivedOriginals7:7,historical1053:{unchanged:1051,authorizedDeltas:2,archivedOriginalsVerified:true},readmes:{main:state(main).readme,worktree:state(root).readme},manifests,r3Absent:true};
if(mode==='initial') {
  const later=git(root,'diff','--name-only','f09e69a6511a5772ea9052da7509a8930ae88d17','HEAD');
  assert.ok(!later || later.split('\n').every(file=>file.startsWith('tasks/evidencias/validacao-zoom-nativo/')),'Only this evidence folder may follow the fixed candidate');
  assert.equal(git(root,'diff','HEAD','--'),'');
  assert.ok(!fs.existsSync(runtime));
  fs.mkdirSync(runtime);
  const files=git(root,'ls-files').split('\n').map(file=>({file,sha256:hash(path.join(root,file))}));
  fs.writeFileSync(path.join(runtime,'initial.json'),JSON.stringify({at:new Date(),root,runtime,main:state(main),publication:state(publication),worktree:state(root),summary,files},null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify({mode,currentTracked:files.length,...summary}));
} else if(mode==='final') {
  const initial=read(path.join(runtime,'initial.json'));
  for(const item of initial.files) assert.equal(hash(path.join(root,item.file)),item.sha256,item.file);
  assert.deepEqual(state(main),initial.main);
  assert.deepEqual(state(publication),initial.publication);
  assert.deepEqual(manifests,initial.summary.manifests);
  const receipt={at:new Date(),mode,currentTrackedUnchanged:initial.files.length,...summary,main:state(main),publication:state(publication),worktree:state(root)};
  const target=path.join(runtime,'preservation-final-'+Date.now()+'.json');
  fs.writeFileSync(target,JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify({...receipt,receipt:target}));
} else throw Error('Expected initial or final');

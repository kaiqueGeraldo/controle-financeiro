import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const directory = path.dirname(fileURLToPath(import.meta.url));
const file = path.join(directory, 'working-tree-inicial.patch');
const original = fs.readFileSync(file);
const content = original.toString('utf8');
const start = content.indexOf('diff --git a/README.md b/README.md');
if (start < 0) throw new Error('README hunk already excluded');
const next = content.indexOf('\ndiff --git ', start + 1);
if (next < 0) throw new Error('Unexpected patch boundaries');
const backup = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'cf015-initial-patch-')), 'working-tree-inicial-completo.patch');
fs.writeFileSync(backup, original, { flag: 'wx' });
const scoped = content.slice(0, start) + content.slice(next + 1);
fs.writeFileSync(file, scoped);
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const report = { reason: 'Não versionar nem mesmo como patch a alteração alheia do README. Referência inicial completa preservada localmente, sem alterar README ou hunks do candidato.', originalLocalBackup: backup, originalSha256: sha256(original), scopedSha256: sha256(fs.readFileSync(file)), excludedPath: 'README.md' };
fs.writeFileSync(path.join(directory, 'preservacao-patch-inicial.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));

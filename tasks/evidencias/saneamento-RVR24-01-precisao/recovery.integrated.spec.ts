import { expect, test } from "@playwright/test";
import { registerSyntheticUser, syntheticUser } from "./support/synthetic-auth";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

test("NG-01 exact committed snapshot survives lost response, replay and recovery across reload", async ({ page }) => {
  const out = process.env.CF_REVIEW_EVIDENCE!;
  const tag = `${process.env.CF_E2E_NAMESPACE}-precision`;
  const exact = '"quantity":999999999999.99999999';
  await page.clock.setFixedTime(new Date("2027-01-15T12:00:00Z"));
  await registerSyntheticUser(page, syntheticUser("A", tag));
  const accountResponse = await page.request.post("/api/accounts", { data: { name: tag, type: "CHECKING", initialBalance: 1000, color: "BLUE" } });
  expect(accountResponse.ok()).toBe(true);
  const account = await accountResponse.json();
  const assetResponse = await page.request.post("/api/investments", { data: { name: tag, ticker: "NGMAX", type: "FIXED_INCOME", openingQuantity: "999999999999.99999999", openingCost: "1.00", openingValue: "1.00", valuationDate: "2027-01-15", valuationSource: "SYNTHETIC" } });
  expect(assetResponse.ok()).toBe(true);
  writeFileSync(join(out, "opening-raw.json"), await assetResponse.text());
  await page.goto("/investimentos");
  await page.getByText("NGMAX", { exact: true }).click();
  await page.getByRole("button", { name: "Aportar", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "NGMAX - Operação", exact: true });
  await modal.getByRole("button", { name: "Resgatar", exact: true }).click();
  await modal.getByLabel("Valor informado").fill("1.00");
  await modal.getByLabel("Conta", { exact: true }).selectOption(account.id);
  let uiPosts = 0;
  let command: Record<string, unknown> = {};
  await page.route("**/api/investments/operation", async route => {
    uiPosts++;
    command = route.request().postDataJSON();
    const response = await route.fetch(); // actual commit, then drop only the delivery
    expect(response.ok()).toBe(true);
    const body = await response.text();
    writeFileSync(join(out, "operation-raw.json"), body);
    expect(body).toContain(exact);
    await route.fulfill({ status: 502, contentType: "application/json", body: '{"message":"Synthetic response loss after commit"}' });
  });
  await modal.getByRole("button", { name: "Confirmar Operação", exact: true }).click();
  await expect(modal.getByRole("button", { name: "Consultar recibo" })).toBeVisible();
  await expect(modal.getByRole("button", { name: "Confirmar Operação", exact: true })).toBeDisabled();
  const saved = await page.evaluate(() => Object.entries(sessionStorage).filter(([key]) => key.startsWith("cf-creation:")));
  expect(saved).toHaveLength(1);
  expect(JSON.parse(saved[0][1]).command).toEqual(command);
  const state = async () => {
    const response = await page.request.get("/api/rv24-probe/state");
    expect(response.ok()).toBe(true);
    const value = await response.json();
    expect(value.raw_operations).toEqual([{ quantity: "999999999999.99999999" }]);
    expect(value.raw_receipts).toEqual([{ quantity: "999999999999.99999999" }]);
    expect(value.accounts).toEqual([{ balance: 1001 }]);
    expect(value.operations).toHaveLength(1);
    expect(value.operations[0].total_value).toBe(1);
    expect(value.receipts).toEqual([{ id: command.operationId, gross: 1 }]);
    expect(value.bank).toHaveLength(1);
    expect(value.bank[0].amount).toBe(1);
    return value;
  };
  const committed = await state();
  // APIRequestContext bypasses page.route: a deliberate replay, same payload and UUID.
  const replay = await page.request.post("/api/investments/operation", { data: command });
  expect(replay.ok()).toBe(true);
  const replayRaw = await replay.text();
  writeFileSync(join(out, "replay-raw.json"), replayRaw);
  expect(replayRaw).toContain(exact);
  const afterReplay = await state();
  const receiptUrl = `**/api/financial-intents/${command.operationId}`;
  await page.route(receiptUrl, async route => {
    const response = await route.fetch();
    expect(response.ok()).toBe(true);
    const body = await response.text();
    expect(body).toContain(exact);
    writeFileSync(join(out, "receipt-raw.json"), body);
    const adulterated = body.replace(exact, '"quantity":1000000000000.00000000');
    writeFileSync(join(out, "receipt-adulterated.json"), adulterated);
    await route.fulfill({ response, body: adulterated });
  });
  const badGet = page.waitForResponse(response => response.url().endsWith(`/api/financial-intents/${command.operationId}`));
  await modal.getByRole("button", { name: "Consultar recibo" }).click();
  await badGet;
  await expect(modal.getByRole("button", { name: "Consultar recibo" })).toBeEnabled();
  expect(await page.evaluate(() => Object.entries(sessionStorage).filter(([key]) => key.startsWith("cf-creation:")))).toEqual(saved);
  await page.unroute(receiptUrl);
  await page.reload();
  await page.getByText("NGMAX", { exact: true }).click();
  await page.getByRole("button", { name: "Aportar", exact: true }).click();
  await expect(modal.getByRole("button", { name: "Consultar recibo" })).toBeVisible();
  await modal.getByRole("button", { name: "Consultar recibo" }).click();
  await expect(modal).toHaveCount(0);
  await page.reload();
  await page.getByText("NGMAX", { exact: true }).click();
  expect(await page.evaluate(() => Object.keys(sessionStorage).filter(key => key.startsWith("cf-creation:")))).toHaveLength(0);
  const recovered = await state();
  expect(uiPosts).toBe(1);
  const positions = await (await page.request.get("/api/investments")).json();
  expect(positions).toEqual(expect.arrayContaining([expect.objectContaining({ ticker: "NGMAX", quantity: 0 })]));
  writeFileSync(join(out, "precision-state.json"), JSON.stringify({ command, uiPosts, explicitReplayPosts: 1, totalMutationRequests: 2, committed, afterReplay, recovered, savedBeforeRecovery: saved, pendingAfterRecovery: [], positions }, null, 2));
});
